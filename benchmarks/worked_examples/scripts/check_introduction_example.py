"""Run the introductory listing with Culsma 1.0.7 and render its declared subject label.

Raw outputs are retained. Only the displayed subject identifier is resolved to
its container label, using the observation's resolved_sample runtime reference.
"""
import argparse
import hashlib
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--culsma-cli', required=True, type=Path)
    parser.add_argument('--program', type=Path, help='Exported introductory program')
    parser.add_argument('--output', type=Path, default=ROOT / 'output/introduction_example')
    parser.add_argument('--tex-output-dir', type=Path, default=ROOT / 'sections/generated')
    args = parser.parse_args()
    if args.program:
        source_text = args.program.read_text()
    else:
        text = (ROOT / 'sections/01_introduction.tex').read_text()
        match = re.search(
            r'\\begin\{lstlisting\}\[[^\n]*label=\{lst:lysate-introduction\}\]\n'
            r'(.*?)\\end\{lstlisting\}', text, re.S)
        if match is None:
            raise ValueError('Introductory listing not found')
        source_text = match[1]
    args.output.mkdir(parents=True, exist_ok=True)
    args.tex_output_dir.mkdir(parents=True, exist_ok=True)
    source = args.output / 'lysate.culs'
    source.write_text(source_text)
    report_path = args.output / 'report.json'
    artifacts_dir = args.output / 'artifacts'
    subprocess.run([str(args.culsma_cli), str(source), '--output', str(report_path),
                    '--artifacts-dir', str(artifacts_dir)],
                   check=True, capture_output=True, text=True)
    report = json.loads(report_path.read_text())
    assert report['ok']
    execution = report['report']['execution']
    assert execution['failed_steps'] == execution['skipped_steps'] == 0
    assert execution['diagnostic_count'] == 0
    products = {p['name']: p for p in report['report']['materials']['final_products']}
    assert products['ClarifiedLysate']['volume_uL'] == 100
    assert products['DebrisWaste']['count_cells'] == 100000
    assert products['LysisTube']['volume_uL'] == 60
    observation = report['returns']['entry']['value']
    assert observation['kind'] == 'data_ref'
    assert observation['contract_kind'] == 'fluorescence'
    assert all(value is None for value in observation['result'].values())
    run = json.loads((artifacts_dir / 'run.json').read_text())
    containers = run['state']['artifacts']['material_state']['containers']
    subject_id = observation['resolved_sample']
    label = containers[subject_id]['metadata']['label']
    assert label == 'ClarifiedLysate'
    internal_name = observation['subject_ref']['name']
    console = subprocess.check_output([str(args.culsma_cli), str(source)], text=True)
    (args.output / 'console.raw.txt').write_text(console)
    old_line = f'    subject: {internal_name}'
    assert console.splitlines().count(old_line) == 1
    rendered = '\n'.join(f'    subject: {label}' if line == old_line else line
                         for line in console.splitlines()) + '\n'
    (args.output / 'console.txt').write_text(rendered)
    version = subprocess.check_output([
        str(args.culsma_cli.parent / 'python'), '-c',
        "from importlib.metadata import version; print(version('culsma'))"], text=True).strip()
    assert version == '1.0.7', version
    summary = {
        'culsma_version': version, 'ok': True, 'execution': execution,
        'input_sha256': hashlib.sha256(source_text.encode()).hexdigest(),
        'renderer_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        'display_subject': {'runtime_reference': subject_id, 'label': label},
        'checks': {'clarified_volume_uL': 100, 'retained_cell_count': 100000,
                   'remaining_supernatant_uL': 60, 'measurement_fields_unset': True},
    }
    (args.output / 'summary.json').write_text(json.dumps(summary, indent=2) + '\n')
    output = args.tex_output_dir / 'lysate_execution_result.tex'
    output.write_text('\n'.join([
        '% Generated by scripts/check_introduction_example.py; subject resolved to declared container label.',
        r'\begin{lstlisting}[language={},basicstyle=\footnotesize\ttfamily,float=tp,caption={Compact execution result for the lysate clarification example, with the observation subject shown by its declared container label.},label={lst:lysate-execution-result}]',
        rendered.rstrip(), r'\end{lstlisting}',
    ]) + '\n')
    print(f'Introduction example passed; wrote {output}')


if __name__ == '__main__':
    main()
